def database_write_expert(db, request):
    system_prompt = """ You are a Database Write Expert. Your task is to understand requests to add skills to a person's resume.

    Extract these three details from the user's request:
    1. Skill name
    2. Skill level (1 to 10)
    3. Experience name

    Return ONLY one line in this format:
    skill_name|skill_level|experience_name

    Example: SQL|7|Computer Engineering Studies

    Do not return Python code, SQL, markdown, or explanations.
    The experience name must match the actual name in the resume.
    Do not include generic words such as "experience" in the experience name.
    For example, "Frontend development training experience" means "Frontend development training".
    """
 
    response = send_message(request, system_prompt).strip()

    parts = response.split("|", 2)

    if len(parts) != 3:
      raise ValueError(f"Invalid WRITE expert response: {response}")

    skill_name, skill_level, experience_name = [
      item.strip() for item in parts
    ]

    skill_level = int(skill_level)

    print("Database Write Expert skill:", skill_name)

    return skill_name, skill_level, experience_name

def coordinator_agent(db, user_message):
    roles = db.query(
        "SELECT system_prompt FROM llm_roles WHERE role_name = ?",
        ("Orchestrator",)
     )

    system_prompt = roles[0]["system_prompt"] + """
     Return ONLY one word:
     READ - if the user only asks about the resume.
     WRITE - if the user wants to add or save a skill.
     BOTH - if the user wants to check something first and add a skill if missing.
     Examples:
     "Add Git with level 8 to my Frontend development training experience." -> WRITE
     "Add SQL as a skill with level 7." -> WRITE
     "What programming skills does this person have?" -> READ

     If the user asks to add, insert, create, or save a skill, always return WRITE.
     Return exactly READ, WRITE, or BOTH. No explanations.
     """

    decision = send_message(user_message, system_prompt)
    return decision.strip().upper()